/** The staging subfolder exports are written to, next to the staged vault tree. */
const OUTPUT_DIR = '__blueplm_output'

export type OutputProgressPhase =
  | 'checking'
  | 'staging'
  | 'retargeting'
  | 'exporting'
  | 'uploading'
  | 'recording'

export interface OutputProgress {
  phase: OutputProgressPhase
  completed?: number
  total?: number
}

export interface EnsureVersionOutputOptions {
  /** STEP and STL: the configuration to export; omitted or null = the saved one. */
  configuration?: string | null
  /**
   * Generate again even when an output is recorded. Only an administrator's result replaces the
   * recorded one; anyone else gets the recorded output back (`cached`).
   */
  regenerate?: boolean
  onProgress?: (progress: OutputProgress) => void
}

export type EnsureVersionOutputResult =
  | { status: 'cached' | 'generated'; output: VersionOutput }
  /** This machine cannot generate it (no service, outdated service, no full SOLIDWORKS). */
  | { status: 'needs_solidworks'; reason: PdfUnavailableReason }
  /** BluePLM Web: outputs are generated by the desktop app only. */
  | { status: 'desktop_only' }
  /** The file cannot have this kind (a PDF of a part, a configuration on IGES, ...). */
  | { status: 'unsupported' }
  /**
   * `errorCode` is the service's or one of: NOT_FOUND, STAGING, SAME_NAME_OPEN (a document of
   * the same name is open in SOLIDWORKS; try again once it is closed), RETARGET_FAILED,
   * EXPORT_FAILED, READ_FAILED, UPLOAD_FAILED, OUTPUT_EXISTS, NOT_UPLOADER, NO_EDIT_PERMISSION.
   */
  | { status: 'failed'; error: string; errorCode?: string; openDocuments?: string[] }

function base64ToArrayBuffer(base64: string): ArrayBuffer {
  const binary = atob(base64)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  return bytes.buffer
}

function localVaultRoots(): string[] {
  const state = usePDMStore.getState()
  const roots = new Set<string>()
  for (const vault of state.connectedVaults) if (vault.localPath) roots.add(vault.localPath)
  if (state.vaultPath) roots.add(state.vaultPath)
  return [...roots]
}

/** Part number and description of a file from the loaded vault rows, for its output's name. */
function loadedFileMetadata(fileId: string | null): { partNumber: string | null; description: string | null } {
  if (!fileId) return { partNumber: null, description: null }
  const file = usePDMStore.getState().files.find((f) => f.pdmData?.id === fileId)
  return {
    partNumber: file?.pdmData?.part_number ?? null,
    description: file?.pdmData?.description ?? null,
  }
}

async function pdfOutput(fileVersionId: string): Promise<VersionOutput | null> {
  const outputs = await listOutputsForVersions([fileVersionId])
  return outputs.get(fileVersionId)?.find((o) => o.kind === 'pdf') ?? null
}

async function ensurePdf(
  fileVersionId: string,
  options: EnsureVersionOutputOptions,
): Promise<EnsureVersionOutputResult> {
  if (options.configuration) return { status: 'unsupported' }
  const result = await ensureDrawingPdf(fileVersionId, (p) => options.onProgress?.(p), {
    regenerate: options.regenerate,
  })
  switch (result.status) {
    case 'cached':
    case 'generated': {
      const output = await pdfOutput(fileVersionId)
      if (!output) return { status: 'failed', error: 'The PDF was not recorded', errorCode: 'NOT_FOUND' }
      return { status: result.status, output }
    }
    case 'not_a_drawing':
      return { status: 'unsupported' }
    case 'needs_solidworks':
      return { status: 'needs_solidworks', reason: result.reason }
    case 'failed':
      return { status: 'failed', error: result.error, errorCode: result.errorCode, openDocuments: result.openDocuments }
  }
}

/**
 * The output of `kind` for a checked-in version, generating it when none is recorded. Never
 * throws: every failure comes back as `failed`.
 */
export async function ensureVersionOutput(
  fileVersionId: string,
  kind: VersionOutputKind,
  options: EnsureVersionOutputOptions = {},
): Promise<EnsureVersionOutputResult> {
  options.onProgress?.({ phase: 'checking' })
  // Only an administrator's result can replace a recorded output (the record RPCs refuse anyone
  // else), so a non-administrator's Regenerate is an ordinary ensure: the recorded output back.
  if (options.regenerate && usePDMStore.getState().getEffectiveRole() !== 'admin') {
    options = { ...options, regenerate: false }
  }
  try {
    if (kind === 'pdf') return await ensurePdf(fileVersionId, options)
    const configuration = options.configuration?.trim() || null
    if (configuration && !kindTakesConfiguration(kind)) return { status: 'unsupported' }

    const cached = options.regenerate ? null : await getModelOutput(fileVersionId, kind, configuration)
    if (cached) return { status: 'cached', output: cached }
    if (!hasDesktop() || !window.electronAPI) return { status: 'desktop_only' }

    const closure = await fetchMergedClosure([fileVersionId])
    const root = closure.files.find((f) => f.fileVersionId === fileVersionId)
    if (!root) return { status: 'failed', error: 'File version not found', errorCode: 'NOT_FOUND' }
    if (!supportsOutputKind(root.filePath, kind)) return { status: 'unsupported' }
    if (configuration && !kindTakesConfiguration(kind, root.filePath)) return { status: 'unsupported' }

    const unavailable = await pdfRenderUnavailableReason()
    if (unavailable) return { status: 'needs_solidworks', reason: unavailable }

    return await exportAndRecord(fileVersionId, kind, configuration, closure, options)
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err)
    log.warn('[Outputs]', 'Version output failed', { fileVersionId, kind, error: message })
    if (err instanceof VersionOutputRpcError) {
      return { status: 'failed', error: message, errorCode: err.code }
    }
    return { status: 'failed', error: message }
  }
}

type ExportCall = { success: boolean; outputFile?: string; error?: string; errorCode?: string }

/** Run the service export of `kind` for the staged file into `outputPath` (a file path). */
async function runExport(
  kind: ModelOutputKind,
  stagedPath: string,
  outputPath: string,
  configuration: string | null,
): Promise<ExportCall> {
  const sw = window.electronAPI!.solidworks
  const configs = configuration ? { configurations: [configuration] } : {}
  switch (kind) {
    case 'step': {
      const r = await sw.exportStep(stagedPath, { outputPath, ...configs })
      return { success: r.success, outputFile: r.data?.exportedFiles?.[0], error: r.error }
    }
    case 'stl': {
      const r = await sw.exportStl(stagedPath, { outputPath, ...configs })
      return { success: r.success, outputFile: r.data?.exportedFiles?.[0], error: r.error }
    }
    case 'iges': {
      const r = await sw.exportIges(stagedPath, { outputPath })
      return { success: r.success, outputFile: r.data?.outputFile, error: r.error }
    }
    case 'dxf': {
      const r = await sw.exportDxf(stagedPath, outputPath)
      return { success: r.success, outputFile: r.data?.outputFile, error: r.error }
    }
  }
}

/** The first part or assembly a staged drawing references that is on disk, with the configuration its views use. */
async function drawingModel(drawingPath: string): Promise<{ path: string; configuration: string | null } | null> {
  const result = await window.electronAPI!.solidworks.getReferences(drawingPath, 'background')
  if (!result.success || !result.data) return null
  for (const ref of result.data.references) {
    const type = ref.fileType?.toLowerCase()
    if ((type !== 'part' && type !== 'assembly') || !ref.exists) continue
    return { path: ref.path, configuration: ref.configurations?.[0] ?? ref.configuration ?? null }
  }
  return null
}

async function exportAndRecord(
  fileVersionId: string,
  kind: ModelOutputKind,
  configuration: string | null,
  closure: MergedClosure,
  options: EnsureVersionOutputOptions,
): Promise<EnsureVersionOutputResult> {
  const api = window.electronAPI!
  const orgId = requireOrgId()
  const root = closure.files.find((f) => f.fileVersionId === fileVersionId)!
  const onProgress = options.onProgress

  const staging = await api.reviewPackage.createStagingDir()
  if (!staging.success || !staging.path) {
    return { status: 'failed', error: staging.error ?? 'No staging folder', errorCode: 'STAGING' }
  }
  const stagingDir = staging.path

  try {
    // A same-named document already open in SOLIDWORKS would be exported instead of the staged one.
    const open = await api.solidworks.getOpenDocuments({ includeComponents: true })
    const clashes = openDocumentNameClashes(
      closure.files.map((f) => f.fileName),
      (open.data?.documents ?? []).map((doc) => doc.filePath),
      stagingDir,
    )
    if (clashes.length > 0) {
      return { status: 'failed', errorCode: 'SAME_NAME_OPEN', error: clashes.join(', '), openDocuments: clashes }
    }

    const staged = await stageFiles(closure.files, stagingDir, {
      orgId,
      onProgress: (p) => onProgress?.({ phase: 'staging', completed: p.completed, total: p.total }),
    })
    const failed = staged.filter((s) => s.status === 'failed')
    if (failed.length > 0) {
      return {
        status: 'failed',
        errorCode: 'STAGING',
        error: failed.map((f) => `${f.packagePath}: ${f.error ?? 'failed'}`).join('; '),
      }
    }
    const source = staged.find((s) => s.file.fileVersionId === fileVersionId)!

    onProgress?.({ phase: 'retargeting' })
    const retarget = await api.solidworks.retargetReferences({
      packageRoot: stagingDir,
      vaultRoots: localVaultRoots(),
    })
    if (!retarget.success || !retarget.data) {
      return {
        status: 'failed',
        errorCode: retarget.errorCode ?? 'RETARGET_FAILED',
        error: retarget.error ?? 'Retargeting failed',
      }
    }
    const retargetClean =
      retarget.data.summary.failed === 0 && retarget.data.summary.missingReferences === 0

    // A drawing's STEP exports the model its views show, from the staged (retargeted) copy.
    let exportPath = source.localPath
    let exportConfiguration = configuration
    if (kind === 'step' && isDrawingFile(root.filePath)) {
      const model = await drawingModel(source.localPath)
      if (!model) {
        return { status: 'failed', errorCode: 'NO_MODEL', error: 'The drawing shows no part or assembly' }
      }
      exportPath = model.path
      exportConfiguration = model.configuration
    }

    const meta = loadedFileMetadata(root.fileId)
    const fileName = outputFileName(
      orgExportFilenamePattern(usePDMStore.getState().organization),
      {
        filename: baseNameOf(root.fileName || root.filePath),
        config: configuration,
        partNumber: meta.partNumber,
        revision: root.revision,
        description: meta.description,
      },
      outputExtension(kind),
    )

    onProgress?.({ phase: 'exporting' })
    const exported = await runExport(
      kind,
      exportPath,
      joinLocalPath(stagingDir, `${OUTPUT_DIR}/${fileName}`),
      exportConfiguration,
    )
    if (!exported.success || !exported.outputFile) {
      return {
        status: 'failed',
        errorCode: exported.errorCode ?? 'EXPORT_FAILED',
        error: exported.error ?? `${kind.toUpperCase()} export failed`,
      }
    }

    onProgress?.({ phase: 'uploading' })
    const read = await api.reviewPackage.readStagedFile(exported.outputFile)
    if (!read.success || read.data === undefined) {
      return { status: 'failed', errorCode: 'READ_FAILED', error: read.error ?? 'Export unreadable' }
    }
    const uploaded = await uploadFile(orgId, base64ToArrayBuffer(read.data))
    if (uploaded.error || !uploaded.hash) {
      return { status: 'failed', errorCode: 'UPLOAD_FAILED', error: uploaded.error ?? 'Upload failed' }
    }

    onProgress?.({ phase: 'recording' })
    const closureExact = closure.exact && retargetClean
    try {
      await recordVersionOutput({
        fileVersionId,
        kind,
        configuration,
        storageHash: uploaded.hash,
        fileSize: uploaded.size,
        fileName,
        closureExact,
      })
    } catch (err) {
      // Someone else generated this output first; theirs stands.
      if (err instanceof VersionOutputRpcError && err.code === 'OUTPUT_EXISTS') {
        const theirs = await getModelOutput(fileVersionId, kind, configuration)
        if (theirs) return { status: 'cached', output: theirs }
      }
      throw err
    }

    const output = await getModelOutput(fileVersionId, kind, configuration)
    if (!output) return { status: 'failed', error: 'The output was not recorded', errorCode: 'NOT_FOUND' }
    log.info('[Outputs]', 'Version output generated', {
      fileVersionId,
      kind,
      file: root.filePath,
      version: root.version,
      configuration,
      closureExact,
      bytes: uploaded.size,
    })
    return { status: 'generated', output }
  } finally {
    const removed = await api.reviewPackage.removeStagingDir(stagingDir)
    if (!removed.success) {
      log.warn('[Outputs]', 'Could not remove the output staging folder', {
        stagingDir,
        error: removed.error,
      })
    }
  }
}
