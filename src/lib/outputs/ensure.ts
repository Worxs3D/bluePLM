/**
 * The output of a checked-in version: generated once, stored content-addressed, reused by everyone.
 *
 * `ensureVersionOutput` returns the recorded output when there is one. A drawing PDF is
 * `ensureDrawingPdf` (reviews and inspection reports use the same render). Any other kind, on a
 * machine with SOLIDWORKS, stages the version and its dependency closure in a temp folder exactly
 * as the PDF render does (never from a working copy), points the staged files at each other
 * (`retargetReferences`), exports through the SOLIDWORKS service into the staging folder, uploads
 * the file to the vault bucket by content hash, records it against the version
 * (`file_version_output_record`) and removes the temp folder. Without SOLIDWORKS it says so
 * (`needs_solidworks`) and changes nothing.
 *
 * A drawing's STEP is the STEP of the part or assembly its views show (the first model reference
 * of the staged drawing, in the configuration the views use), recorded against the drawing's
 * version and named with the drawing's metadata, as "Export STEP (Model)" names a local copy.
 */

